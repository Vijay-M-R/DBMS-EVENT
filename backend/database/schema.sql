-- Trigger 1: Validate Cross-Table Slot and Service Provider Alignment on Booking
CREATE OR REPLACE FUNCTION validate_booking_integrity()
RETURNS TRIGGER AS $$
DECLARE
    v_service_provider_id BIGINT;
    v_slot_provider_id BIGINT;
    v_slot_status VARCHAR(20);
    v_provider_status VARCHAR(20);
BEGIN
    -- 1. Extract service provider
    SELECT provider_id INTO v_service_provider_id FROM services WHERE service_id = NEW.service_id;
    IF v_service_provider_id IS NULL THEN
        RAISE EXCEPTION 'Referenced service ID % does not exist.', NEW.service_id;
    END IF;

    -- 2. Extract slot provider and status
    SELECT provider_id, slot_status INTO v_slot_provider_id, v_slot_status FROM availability_slots WHERE slot_id = NEW.slot_id;
    IF v_slot_provider_id IS NULL THEN
        RAISE EXCEPTION 'Referenced slot ID % does not exist.', NEW.slot_id;
    END IF;

    -- 3. Verify slot belongs to service provider
    IF v_service_provider_id <> v_slot_provider_id THEN
        RAISE EXCEPTION 'Slot ID % belongs to provider %, but service ID % belongs to provider %.', 
            NEW.slot_id, v_slot_provider_id, NEW.service_id, v_service_provider_id;
    END IF;

    -- 4. Check if provider is suspended
    SELECT verification_status INTO v_provider_status FROM provider_profiles WHERE provider_id = v_service_provider_id;
    IF v_provider_status = 'SUSPENDED' THEN
        RAISE EXCEPTION 'Cannot book service. Provider % is currently suspended.', v_service_provider_id;
    END IF;

    -- 5. If new booking, verify slot is available
    IF TG_OP = 'INSERT' AND NEW.booking_status IN ('PENDING', 'ACCEPTED') THEN
        IF v_slot_status <> 'AVAILABLE' THEN
            RAISE EXCEPTION 'Cannot book slot ID %. Current slot status is %.', NEW.slot_id, v_slot_status;
        END IF;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_validate_booking_integrity
BEFORE INSERT OR UPDATE ON bookings
FOR EACH ROW
EXECUTE FUNCTION validate_booking_integrity();

-- Trigger 2: Sync Slot Status with Booking Lifecycle
CREATE OR REPLACE FUNCTION sync_slot_status_on_booking()
RETURNS TRIGGER AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF NEW.booking_status IN ('PENDING', 'ACCEPTED') THEN
            UPDATE availability_slots SET slot_status = 'BOOKED' WHERE slot_id = NEW.slot_id;
        END IF;
    ELSIF TG_OP = 'UPDATE' THEN
        -- When a booking transitions from active to cancelled/rejected, release the slot
        IF OLD.booking_status IN ('PENDING', 'ACCEPTED') AND NEW.booking_status IN ('CANCELLED', 'REJECTED') THEN
            UPDATE availability_slots SET slot_status = 'AVAILABLE' WHERE slot_id = NEW.slot_id;
        ELSIF OLD.booking_status IN ('CANCELLED', 'REJECTED') AND NEW.booking_status IN ('PENDING', 'ACCEPTED') THEN
            UPDATE availability_slots SET slot_status = 'BOOKED' WHERE slot_id = NEW.slot_id;
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_sync_slot_status
AFTER INSERT OR UPDATE ON bookings
FOR EACH ROW
EXECUTE FUNCTION sync_slot_status_on_booking();

-- Trigger 3: Validate Review Eligibility (Completed Booking & Matching Customer)
CREATE OR REPLACE FUNCTION validate_review_eligibility()
RETURNS TRIGGER AS $$
DECLARE
    v_booking_status VARCHAR(20);
    v_booking_customer_id BIGINT;
BEGIN
    SELECT booking_status, customer_id INTO v_booking_status, v_booking_customer_id 
    FROM bookings WHERE booking_id = NEW.booking_id;

    IF v_booking_status IS NULL THEN
        RAISE EXCEPTION 'Booking ID % does not exist.', NEW.booking_id;
    END IF;

    IF v_booking_status <> 'COMPLETED' THEN
        RAISE EXCEPTION 'Reviews can only be submitted for COMPLETED bookings. Current status is %.', v_booking_status;
    END IF;

    IF v_booking_customer_id <> NEW.customer_id THEN
        RAISE EXCEPTION 'Review customer ID % does not match booking customer ID %.', NEW.customer_id, v_booking_customer_id;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_validate_review_eligibility
BEFORE INSERT ON reviews
FOR EACH ROW
EXECUTE FUNCTION validate_review_eligibility();

-- Trigger 4: Automatically Update Provider Average Rating and Total Reviews
CREATE OR REPLACE FUNCTION update_provider_rating_stats()
RETURNS TRIGGER AS $$
DECLARE
    v_provider_id BIGINT;
    v_avg_rating NUMERIC(3, 2);
    v_count INT;
BEGIN
    -- Determine target provider ID via booking and service
    IF TG_OP = 'DELETE' THEN
        SELECT s.provider_id INTO v_provider_id
        FROM bookings b
        JOIN services s ON b.service_id = s.service_id
        WHERE b.booking_id = OLD.booking_id;
    ELSE
        SELECT s.provider_id INTO v_provider_id
        FROM bookings b
        JOIN services s ON b.service_id = s.service_id
        WHERE b.booking_id = NEW.booking_id;
    END IF;

    -- Calculate aggregates across all reviews for this provider
    SELECT COALESCE(ROUND(AVG(r.rating), 2), 0.00), COUNT(r.review_id)
    INTO v_avg_rating, v_count
    FROM reviews r
    JOIN bookings b ON r.booking_id = b.booking_id
    JOIN services s ON b.service_id = s.service_id
    WHERE s.provider_id = v_provider_id;

    -- Update provider profile
    UPDATE provider_profiles
    SET average_rating = v_avg_rating,
        total_reviews = v_count
    WHERE provider_id = v_provider_id;

    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_update_provider_ratings
AFTER INSERT OR UPDATE OR DELETE ON reviews
FOR EACH ROW
EXECUTE FUNCTION update_provider_rating_stats();

